function numberType(number) {
      var number = number
      if (number > 0) {
            console.log("This is positive")
      }
      else if (number < 0) {
            console.log("This is negative")
      } else if (number == 0) {
            console.log("This is natural number")
     }
}
numberType(13)
numberType(0)
numberType(-10)